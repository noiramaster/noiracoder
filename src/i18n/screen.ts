const TABLES: Record<string, ScreenStrings> = { en, es, pt, fr, de, it, ar };

/** Cadena con fallback exacto → base (xx-YY → xx) → inglés. Sin clave → la clave. */
export function screenString(lang: string, key: string): string {
  const norm = (lang || "en").toLowerCase().replace("_", "-");
  const cands = [norm];
  const dash = norm.indexOf("-");
  if (dash > 0) cands.push(norm.slice(0, dash));
  cands.push("en");
  for (const c of cands) {
    const t = TABLES[c];
    if (t && typeof t[key] === "string" && t[key].length > 0) return t[key];
  }
  return key;
}

export function screenStrings(lang: string): { lang: string; strings: ScreenStrings } {
  const norm = (lang || "en").toLowerCase().replace("_", "-");
  const base = norm.includes("-") ? norm.slice(0, norm.indexOf("-")) : norm;
  const resolved = TABLES[norm] ? norm : TABLES[base] ? base : "en";
  return { lang: resolved, strings: TABLES[resolved] };
}

/** Sustituye {nombre}; lo desconocido se deja tal cual (visible en tests). */
export function renderScreen(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (m, k: string) =>
    Object.prototype.hasOwnProperty.call(vars, k) ? String(vars[k]) : m,
  );
}
